// Hornea todo una vez. Devuelve { der: {...}, izq: {...}, hoja }.
// A escala 1: un dibujo de 22x30 celdas ocupa 22x30 px virtuales.
export function bakeCaballero() {
  const der = {}, izq = {};
  for (const k in FRAMES) {
    der[k] = FRAMES[k].map(rows => bake(rows, M, 1));
    izq[k] = der[k].map(bakeFlip);
  }
  return { der, izq, hoja: bake(HOJA, M, 1) };
}

