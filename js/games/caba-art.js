// EL CABALLERO - el arte del caballero, fotograma a fotograma.
//
// Es el primer juego del arcade con ANIMACION DE VERDAD: cada pose es un
// dibujo distinto, no el mismo sprite estirado. SURVIVAL anima transformando
// el dibujado (surv-anim.js) porque tiene veintiocho criaturas; aqui hay UNA
// figura y se la dibuja a mano, que es lo que pidio el dueño.
//
// LA ESCALA, medida y no supuesta. bake(rows, map, s) devuelve un canvas de
// (ancho*s) x (alto*s) PIXELES, y spr() lo dibuja con drawImage sin tamaño,
// asi que esos pixeles son unidades VIRTUALES: hornear un dibujo de 22x30 a
// escala 2 lo pone de 44x60 en el lienzo, no de 22x30. Por eso aqui se hornea
// a ESCALA 1 y el detalle lo da meta.ss = 2 del motor, que agranda el lienzo
// real sin agrandar nada de lo que se dibuja encima.
//
// El caballero mide 22x30 celdas. Con el suelo en y=222 de un lienzo de
// 600x270, su cabeza queda en 192 y sobre ella hay sitio para un jefe de
// 4 caballeros de alto sin que toque el HUD.

