export function drawCaballero(g, S, x, y, dir, pose, frame) {
  const set = dir >= 0 ? S.der : S.izq;
  const arr = set[pose] || set.idle;
  const cv = arr[Math.min(frame, arr.length - 1)];
  spr(g, cv, x, y - cv.height / 2);
}
